// Cross-origin worker scripts cannot be passed to `new Worker()` directly —
// the browser requires same-origin. Standard workaround (used by the
// WebContainer-style CDNs): fetch the source (CORS) once per page and boot
// it from a blob URL. Memoized so every guest process reuses one fetch.
let workerBlobCache: { base: string; url: string } | null = null;

/** Terminal output line discipline for TTY stdio (termios OPOST/ONLCR): a
 *  real kernel TTY translates NL → CR-NL on OUTPUT, so guest programs that
 *  print bare "\n" still return the cursor to column 0 of the next line.
 *  Host terminals run xterm with convertEol:false (they write \r\n for
 *  their own echo/prompt), which makes the translation load-bearing —
 *  without it every multi-line guest write renders as a staircase. NLs
 *  already preceded by CR pass through untouched (no \r\r\n inflation);
 *  the per-chunk statelessness is safe: a CR|NL split across chunks can
 *  only produce the visually-identical \r\r\n. Piped stdio never passes
 *  through here — pipe consumers get byte-exact output. */
function ttyOut(text: string): string {
  return text.includes('\n') ? text.replace(/(?<!\r)\n/g, '\r\n') : text;
}

/** Wait (bounded) for a registration's worker to become active — a fresh
 *  install runs install→activate (the SW itself skipWaiting+claims); an
 *  already-active registration resolves immediately. Never rejects and
 *  never waits longer than 3s: boot must not hang on SW lifecycle. */
function waitForActive(reg: ServiceWorkerRegistration): Promise<void> {
  const sw = reg.active ?? reg.installing ?? reg.waiting;
  if (!sw || sw.state === 'activated') return Promise.resolve();
  return new Promise<void>((resolve) => {
    const done = () => resolve();
    sw.addEventListener('statechange', () => {
      if (sw.state === 'activated' || sw.state === 'redundant') done();
    });
    setTimeout(done, 3000);
  });
}

/** Per-boot preview session id — routes preview traffic to THIS runtime on
 *  the shared SW (multi-tab determinism). Shape: 6 chars, letter-first, so
 *  it can never be confused with a port number in preview URLs. */
function previewSid(): string {
  // The SW's URL contract is ^[a-z][a-z0-9]{3,11}$ — the FIRST character
  // MUST be a letter. A digit-first sid (possible with the mixed alphabet)
  // silently unroutes every preview fetch ("no route" — found via the
  // same-origin harness, ~30% of sessions).
  const letters = 'abcdefghjkmnpqrstuvwxyz';
  const alphabet = letters + '23456789';
  let sid = '';
  const rand = new Uint8Array(6);
  (globalThis as any).crypto?.getRandomValues?.(rand);
  for (let i = 0; i < 6; i++) {
    const src = i === 0 ? letters : alphabet;
    sid += src[(rand[i] ?? Math.floor(Math.random() * 256)) % src.length];
  }
  return sid;
}

async function resolveWorkerUrl(base: string): Promise<string> {
  const bust = /^https?:/.test(base)
    ? `?v=${OPENCONTAINER_VERSION}` // CDN: version-pinned and immutable
    : `?v=${(globalThis as any).__ocWorkerBust ?? ((globalThis as any).__ocWorkerBust = Date.now())}`;
  const direct = `${base}/kernel-worker.js${bust}`;
  // Same-origin path → spawnable directly, no fetch hop.
  if (!/^https?:/.test(base)) return direct;
  if (workerBlobCache?.base === base) return workerBlobCache.url;
  let res: Response;
  try {
    res = await fetch(direct);
  } catch (err: any) {
    throw new Error(
      `OpenContainer: could not load the kernel worker from ${base} (${err?.message ?? err}). ` +
      'If you are offline or behind a CORS-restricting proxy, self-host the assets and pass { assetsBase: \'/your-path\' }.',
    );
  }
  if (!res.ok) {
    throw new Error(
      `OpenContainer: could not load the kernel worker from ${direct} (HTTP ${res.status}). ` +
      'If the version is not published yet, or you are offline, self-host the assets and pass { assetsBase: \'/your-path\' }.',
    );
  }
  const src = await res.text();
  const url = URL.createObjectURL(new Blob([src], { type: 'text/javascript' }));
  workerBlobCache = { base, url };
  return url;
}

