/**
 * OpenContainer — Main-thread runtime: the PROCESS MANAGER.
 *
 * Every Node.js "process" is one kernel worker. This class owns:
 *   - the process table (pid → worker, stdio spec, parent, children)
 *   - the pipe table (stdio routing between parent and child processes)
 *   - the virtual port registry (which process listens on which port)
 *   - the authoritative in-session VFS snapshot (deltas fan out to every
 *     live process)
 *   - the foreground process (terminal input/stdio + signals)
 *
 * A hidden "shell keeper" process (pid 1) stays alive for the whole session
 * and serves host filesystem RPCs. The VFS is session-scoped (temporary-
 * environment contract): nothing persists across reloads — the host supplies
 * project files at boot of every fresh session.
 */

export interface RuntimeEvents {
  onStdio?(fd: 1 | 2, chunk: string): void;
  onExit?(info: { pid: number; code: number | null; signal: string | null; foreground: boolean }): void;
  onReady?(info: { nodeVersion: string; modules?: number; bootMs?: number }): void;
  onBootProgress?(info: { phase: string; loaded: number; total: number }): void;
  onError?(err: { message: string; stack?: string }): void;
  onFatal?(err: { message: string; stack?: string }): void;
  onAmaroReady?(): void;
  onListen?(info: { port: number; pid: number }): void;
  onUnlisten?(info: { port: number; pid: number }): void;
  onProcessStart?(info: { pid: number; repl: boolean; background: boolean }): void;
  onFsChange?(event: { type: 'rename' | 'change'; filename: string | null }): void;
  onPreviewMessage?(message: unknown): void;
}

export type RuntimeEventMap = {
  stdio: (fd: 1 | 2, chunk: string) => void;
  exit: (info: { pid: number; code: number | null; signal: string | null; foreground: boolean }) => void;
  ready: (info: { nodeVersion: string; modules?: number; bootMs?: number }) => void;
  bootProgress: (info: { phase: string; loaded: number; total: number }) => void;
  error: (err: { message: string; stack?: string }) => void;
  fatal: (err: { message: string; stack?: string }) => void;
  amaroReady: () => void;
  listen: (info: { port: number; pid: number }) => void;
  unlisten: (info: { port: number; pid: number }) => void;
  processStart: (info: { pid: number; repl: boolean; background: boolean }) => void;
  fsChange: (event: { type: 'rename' | 'change'; filename: string | null }) => void;
  previewMessage: (message: unknown) => void;
  /** Preview infrastructure report (v2): which distribution mode was chosen —
   *  'root-scope' (full fidelity), 'scoped' (same-origin package path),
   *  'cdn-bridge' (zero-integration CDN fallback) or 'none'. */
  previewStatus: (info: { mode: 'root-scope' | 'scoped' | 'cdn-bridge' | 'none'; sid?: string; reason?: string }) => void;
};

