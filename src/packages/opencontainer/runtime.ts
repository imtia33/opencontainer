/**
 * Where the kernel worker + runtime blobs are loaded from.
 *
 * Default: jsDelivr, pinned to the installed package version — the
 * WebContainer model (their runtime is fetched at boot from StackBlitz's
 * own origin; the npm package is just the API). jsDelivr serves any file of
 * the npm package with `Access-Control-Allow-Origin: *`, so embedders need
 * to copy or host NOTHING: `npm install opencontainer` is the whole setup.
 *
 * Self-hosting / offline: pass `{ assetsBase: '/my-hosted-path' }` (a path
 * on your own origin that serves the package's `public/opencontainer/`
 * directory) or an absolute URL to any CORS-enabled mirror.
 */
export const DEFAULT_ASSETS_BASE =
  `https://cdn.jsdelivr.net/npm/opencontainer@${OPENCONTAINER_VERSION}/public/opencontainer`;

/** Runtime options (second constructor argument). */
export interface RuntimeOptions {
  /** Base URL that serves `kernel-worker.js` and `runtime/` blobs.
   *  Absolute URL (CORS-enabled) or a same-origin path. Default: the
   *  jsDelivr CDN, pinned to the installed version — zero setup. */
  assetsBase?: string;
}

// Cross-origin worker scripts cannot be passed to `new Worker()` directly —
// the browser requires same-origin. Standard workaround (used by the
// WebContainer-style CDNs): fetch the source (CORS) once per page and boot
// it from a blob URL. Memoized so every guest process reuses one fetch.
let workerBlobCache: { base: string; url: string } | null = null;

async function resolveWorkerUrl(base: string): Promise<string> {
  const bust = /^https?:/.test(base)
    ? `?v=${OPENCONTAINER_VERSION}` // CDN: version-pinned and immutable
    : `?v=${(globalThis as any).__ocWorkerBust ?? ((globalThis as any).__ocWorkerBust = Date.now())}`;
  const direct = `${base}/kernel-worker.js${bust}`;
  // Same-origin path → spawnable directly, no fetch hop.
  if (!/^https?:/.test(base)) return direct;
  if (workerBlobCache?.base === base) return workerBlobCache.url;
  let res: Response;
  try {
    res = await fetch(direct);
  } catch (err: any) {
    throw new Error(
      `OpenContainer: could not load the kernel worker from ${base} (${err?.message ?? err}). ` +
      'If you are offline or behind a CORS-restricting proxy, self-host the assets and pass { assetsBase: \'/your-path\' }.',
    );
  }
  if (!res.ok) {
    throw new Error(
      `OpenContainer: could not load the kernel worker from ${direct} (HTTP ${res.status}). ` +
      'If the version is not published yet, or you are offline, self-host the assets and pass { assetsBase: \'/your-path\' }.',
    );
  }
  const src = await res.text();
  const url = URL.createObjectURL(new Blob([src], { type: 'text/javascript' }));
  workerBlobCache = { base, url };
  return url;
}

export interface ParsedCommand { cmd: string; args: string[] }

interface StdioSpec {
  type: 'tty' | 'pipe' | 'ignore';
  pipeId?: number;
}

interface EntrySpec {
  type: 'main' | 'eval' | 'repl' | 'version';
  path?: string;
  code?: string;
  print?: boolean;
}

interface KernelProcess {
  pid: number;
  parentPid: number | null;
  worker: Worker;
  stdio: StdioSpec[];
  repl: boolean;
  background: boolean;
  exited: boolean;
  exitCode: number | null;
  exitSignal: string | null;
  ready: Promise<void>;
  readyResolve: () => void;
  readyReject: (e: any) => void;
  children: Set<number>;
  pending: Map<number, { resolve: (value?: any) => void; reject: (e: any) => void }>;
}

interface PipeRoute {
  parentPid: number;   // the process holding the read/write end handle
  childPid: number;    // the process whose fd this pipe is
  fd: number;          // 0 = child stdin, 1/2 = child stdout/stderr
}

interface ConnectionRoute {
  ownerPid: number;        // process whose kernel owns connId
  peer: { pid: number; connId: number } | null;  // local pair
  preview: MessagePort | null;                    // preview bridge end
}

/** Host-owned end of a guest process's stdio pipe (facade spawnProgram).
 *  parentPid === 0 in the pipe table marks the HOST as the pipe's reader
 *  (fd 1/2) or writer (fd 0). */
interface HostPipeSink {
  push(bytes: Uint8Array): void;
  close(): void;
}

/** Programmatic (WebContainer-API shape) process handle from spawnProgram. */
export interface ProgramHandle {
  pid: number;
  /** Resolves with the exit code when the process exits. */
  exit: Promise<number>;
  /** Writable stdin pipe (string chunks). */
  input: WritableStream<string>;
  /** Readable stdout pipe. */
  output: ReadableStream<string>;
  /** Readable stdout pipe — WebContainer merges stderr here; to stay
   *  drop-in we do the same (fd1 + fd2 both feed `output`), while
   *  `stderr` (an OpenContainer extension) stays fd2-only. */
  stderr: ReadableStream<string>;
  /** Best-effort terminal-size update (affects TTY-attached children). */
  resize(size: { cols: number; rows: number }): void;
  /** Terminate (SIGTERM semantics — hard worker termination). */
  kill(): void;
}

const MAX_LIVE_PROCESSES = 8;

export class OpenContainerRuntime {
  private processes = new Map<number, KernelProcess>();
  private pipes = new Map<number, PipeRoute>();
  private connections = new Map<number, ConnectionRoute>();
  private ports = new Map<number, { pid: number }>();
  /** Host-owned pipe ends (facade processes): pipeId → sink. */
  private hostPipeSinks = new Map<number, HostPipeSink>();
  private nextHostPipeId = 1_000_000; // never collides with guest pipe ids
  private nextPid = 2;              // 1 = shell keeper
  private nextConnId = 1;
  private listeners = new Map<keyof RuntimeEventMap, Set<(...args: never[]) => void>>();
  private events: RuntimeEvents;

  /** Current shell working directory (the terminal's `cd` state; every
   *  spawned process boots with this as its cwd). */
  private cwd = '/home/project';

  /** In-session VFS snapshot — every mutation from any process folds in
   *  here and fans out to the other live processes. */
  private vfsSnapshot: { dirs: Set<string>; files: Map<string, Uint8Array>; symlinks: Map<string, string> }
    = { dirs: new Set(), files: new Map(), symlinks: new Map() };
  private snapshotDirty = false;
  private persistTimer: ReturnType<typeof setTimeout> | null = null;

  private foregroundPid: number | null = null;
  private bootedOnce = false;
  /** Base URL the kernel worker + runtime blobs load from (see
   *  DEFAULT_ASSETS_BASE). */
  private assetsBase: string;
  /** Resolved spawnable worker URL (direct path or blob URL). */
  private workerUrl: string | null = null;
  ready: Promise<{ nodeVersion: string; modules?: number; bootMs?: number }>;
  exited = false;
  nodeVersion: string | null = null;
  bootMs: number | null = null;
  private _bootStart = 0;
  /** Shell keeper — pid 1; performs OPFS hydration + persistence RPCs. */
  private keeper: KernelProcess | null = null;
  /** fs.watch callbacks (facade fs.watch / embedder watchers). */
  private fsWatchers = new Map<number, (event: { type: 'rename' | 'change'; filename: string | null }) => void>();
  private nextWatchId = 1;
  /** Preview ServiceWorker state (see registerPreview). */
  private previewRegistered = false;
  private previewScript: string | null = null;

  constructor(events: RuntimeEvents = {}, options: RuntimeOptions = {}) {
    this.events = events;
    this.assetsBase = (options.assetsBase ?? DEFAULT_ASSETS_BASE).replace(/\/+$/, '');
    this.ready = new Promise((res, rej) => {
      this._readyResolve = res;
      this._readyReject = rej;
    });
  }
  private _readyResolve!: (v: any) => void;
  private _readyReject!: (e: any) => void;

  // ------------------------------------------------------------------ boot
  async boot(): Promise<{ nodeVersion: string }> {
    if (this.bootedOnce) return this.ready;
    this.bootedOnce = true;
    this._bootStart = performance.now();
    // Resolve the spawnable worker URL first: a same-origin path spawns
    // directly; an absolute (CDN) base is fetched once and booted from a
    // blob URL. Failing here (offline, unpublished version) rejects `ready`
    // with a self-describing error instead of a worker 404.
    try {
      this.workerUrl = await resolveWorkerUrl(this.assetsBase);
    } catch (err: any) {
      this._readyReject(err);
      this.events.onError?.({ message: err?.message ?? String(err) });
      throw err;
    }
    // Preview URL support (server-ready → iframe.src): best-effort, never
    // blocks boot — the runtime works without the SW except for preview
    // URLs (see registerPreview for the failure warning).
    void this.registerPreview().catch(() => { /* warned inside */ });
    // The shell keeper: a real kernel process with no entry (idle). It
    // hydrates the VFS from OPFS on a fresh page load and owns persistence.
    const keeper = this.createProcess({
      pid: 1,
      parentPid: null,
      stdio: [{ type: 'ignore' }, { type: 'ignore' }, { type: 'ignore' }],
      entry: null,
      env: undefined,
      cwd: '/home/project',
      repl: false,
      background: true,
    });
    this.keeper = keeper;
    await keeper.ready;
    return this.ready;
  }

  // -------------------------------------------------------------- processes
  private createProcess(spec: {
    pid: number;
    parentPid: number | null;
    stdio: StdioSpec[];
    entry: EntrySpec | null;
    env?: Record<string, string>;
    cwd?: string;
    argv?: string[];
    repl: boolean;
    background: boolean;
  }): KernelProcess {
    const proc: KernelProcess = {
      pid: spec.pid,
      parentPid: spec.parentPid,
      worker: null as any,
      stdio: spec.stdio,
      repl: spec.repl,
      background: spec.background,
      exited: false,
      exitCode: null,
      exitSignal: null,
      ready: null as any,
      readyResolve: () => {},
      readyReject: () => {},
      children: new Set(),
      pending: new Map(),
    };
    proc.ready = new Promise<void>((res, rej) => {
      proc.readyResolve = res;
      proc.readyReject = rej;
    });

    // Cache-bust: for same-origin dev bases the query defeats HTTP caching
    // of kernel-worker.js across rebuilds (dev + user upgrades); CDN bases
    // are version-pinned in the URL and immutable. The worker URL itself
    // was resolved in boot() (direct path or blob URL).
    const worker = new Worker(this.workerUrl ?? `/opencontainer/kernel-worker.js`, { type: 'module' });
    proc.worker = worker;
    worker.onmessage = (ev: MessageEvent) => this.handleProcessMessage(proc, ev.data);
    worker.onerror = (e) => {
      this.emit('error', { message: e.message });
      if (!proc.exited) {
        proc.exited = true;
        proc.exitCode = 1;
        this.emit('exit', {
          pid: proc.pid, code: 1, signal: null,
          foreground: this.foregroundPid === proc.pid,
        });
      }
      proc.readyReject(new Error(e.message));
    };

    this.processes.set(proc.pid, proc);
    if (spec.parentPid !== null) {
      this.processes.get(spec.parentPid)?.children.add(proc.pid);
    }

    const argv = spec.argv ?? (spec.entry?.type === 'main' && spec.entry.path
      ? ['/usr/local/bin/node', spec.entry.path]
      : ['node']);
    const bootMsg: any = {
      type: 'boot',
      hydrate: this.snapshotPayload(),
      entry: spec.entry,
      stdio: spec.stdio,
      env: spec.env,
      cwd: spec.cwd ?? '/home/project',
      argv,
      pid: spec.pid,
      ppid: spec.parentPid ?? 0,
      // Port mirror: bind() checks EADDRINUSE synchronously in the kernel —
      // the process must know the occupied ports BEFORE its entry runs (a
      // later ports-update races the user code's listen()).
      initialPorts: [...this.ports.keys()],
      // S3.1: embed the runtime index (generated with the blobs) — saves one
      // index.json round trip per worker boot.
      runtimeIndex: RUNTIME_INDEX,
      // Where this build's runtime blobs (.ocrt.gz) are served from. The
      // worker cannot guess it: with the default CDN base the worker's own
      // location is a blob: URL, and the same-origin '/opencontainer'
      // default only holds for self-hosted embeddings.
      runtimeBase: `${this.assetsBase}/runtime`,
    };
    worker.postMessage(bootMsg);
    void proc.ready.catch(() => { /* surfaced via error events */ });
    return proc;
  }

  private handleProcessMessage(proc: KernelProcess, msg: any) {
    switch (msg.type) {
      case 'boot-progress':
        if (proc.pid === 1 || this.foregroundPid === proc.pid) {
          this.emit('bootProgress', { phase: msg.phase ?? '', loaded: msg.loaded ?? 0, total: msg.total ?? 0 });
        }
        break;
      case 'ready': {
        if (msg.hydratedFrom === 'opfs' && msg.vfsSnapshot) {
          this.adoptSnapshot(msg.vfsSnapshot);
        }
        if (proc.pid === 1) {
          this.nodeVersion = msg.nodeVersion;
          this.bootMs = msg.bootMs ?? null;
          (globalThis as any).__ocBootPhases = {
            ...(msg.phases ?? {}),
            mainTotalMs: this._bootStart ? Math.round(performance.now() - this._bootStart) : null,
          };
          this.emit('ready', { nodeVersion: msg.nodeVersion, modules: msg.modules, bootMs: msg.bootMs });
          this._readyResolve({ nodeVersion: msg.nodeVersion, modules: msg.modules, bootMs: msg.bootMs });
        }
        proc.readyResolve();
        break;
      }
      case 'amaro-ready':
        this.emit('amaroReady');
        this.events.onAmaroReady?.();
        break;
      case 'stdio': {
        const fd = (msg.fd ?? 1) as 1 | 2;
        // Piped child output (process.stdout.write with pipe stdio) routes
        // through the pipe table — node semantics: piped bytes belong to the
        // pipe's reader (guest parent or the host), NOT the terminal.
        if (msg.pipeId !== undefined) {
          const route = this.pipes.get(msg.pipeId);
          if (route) {
            this.deliverPipeOutput(msg.pipeId, route, msg.bytes ?? new TextEncoder().encode(msg.chunk ?? ''));
            break;
          }
        }
        if (msg.bytes) {
          this.emit('stdio', fd, new TextDecoder().decode(msg.bytes));
        } else {
          this.emit('stdio', fd, msg.chunk ?? '');
        }
        break;
      }
      case 'pipe-write': {
        // Piped stdio bytes — route by the pipe table: fd 0 = the child's
        // stdin (the parent's writes flow IN); fd 1/2 = the child's output
        // (the parent's read-side handle receives it).
        const route = this.pipes.get(msg.pipeId);
        if (route) {
          if (route.fd === 0) {
            const child = this.processes.get(route.childPid);
            child?.worker.postMessage({
              type: 'stdin', data: undefined, bytes: msg.bytes, pipeId: msg.pipeId,
            });
          } else {
            this.deliverPipeOutput(msg.pipeId, route, msg.bytes);
          }
        }
        break;
      }
      case 'exit': {
        this.onProcessExit(proc, msg.code ?? 0, msg.signal ?? null);
        break;
      }
      case 'eval-done':
      case 'spawn-done':
      case 'resized':
      case 'boot-done':
      case 'write-file-done':
      case 'persist-vfs-done': {
        const p = proc.pending.get(msg.id);
        if (p) { proc.pending.delete(msg.id); p.resolve(); }
        break;
      }
      case 'rpc-result': {
        // Uniform IDE filesystem RPC reply (fs-read/readdir/stat/apply-ops/
        // watch/unwatch/tree/diag). Data-carrying resolve / typed reject.
        const p = proc.pending.get(msg.id);
        if (p) {
          proc.pending.delete(msg.id);
          if (msg.ok) p.resolve(msg.result);
          else p.reject(new FsRpcError(msg.err?.code ?? 'EIO', msg.err?.message ?? 'rpc failed', msg.err?.path));
        }
        break;
      }
      case 'fs-event': {
        // Watcher event from the keeper's VFS (host ops + fanned-out guest
        // deltas both fire real VFS methods → watchers in every kernel).
        const cb = this.fsWatchers.get(msg.watchId);
        if (cb) cb(msg.event ?? {});
        this.emit('fsChange', msg.event ?? {});
        this.events.onFsChange?.(msg.event ?? {});
        break;
      }
      case 'vfs-delta':
        this.applyDeltas(proc, msg.ops ?? []);
        break;
      case 'error': {
        const err = { message: msg.message, stack: msg.stack };
        if (proc.pid === 1 || this.foregroundPid === proc.pid) {
          this.emit('error', err);
        }
        break;
      }
      case 'child-spawn':
        this.onChildSpawn(proc, msg.req);
        break;
      case 'child-kill':
        this.killProcess(msg.pid, msg.signal ?? 'SIGTERM');
        break;
      case 'pipe-close': {
        const route = this.pipes.get(msg.pipeId);
        if (route) {
          if (route.fd === 0) {
            // Parent closed the child's stdin → EOF.
            const child = this.processes.get(route.childPid);
            child?.worker.postMessage({ type: 'stdin-eof' });
          } else if (route.parentPid === 0) {
            // Host-owned read end: the child closed its stdout/stderr.
            this.closeHostPipe(msg.pipeId);
          } else {
            // The write end of a child's stdout/stderr went away.
            const parent = this.processes.get(route.parentPid);
            parent?.worker.postMessage({ type: 'pipe-eof', pipeId: msg.pipeId });
          }
        }
        break;
      }
      case 'tcp-listen': {
        const port = msg.port | 0;
        const existing = this.ports.get(port);
        if (existing && existing.pid !== proc.pid) {
          proc.worker.postMessage({ type: 'listen-failed', listenId: msg.listenId });
        } else {
          this.ports.set(port, { pid: proc.pid });
          this.broadcastPorts();
          this.emit('listen', { port, pid: proc.pid });
        }
        break;
      }
      case 'tcp-unlisten': {
        const port = msg.port | 0;
        const entry = this.ports.get(port);
        if (entry && entry.pid === proc.pid) {
          this.ports.delete(port);
          this.broadcastPorts();
          this.emit('unlisten', { port, pid: proc.pid });
        }
        break;
      }
      case 'tcp-connect': {
        // Outbound localhost connect from this process.
        this.onOutboundConnect(proc, msg);
        break;
      }
      case 'tcp-write': {
        const route = this.connections.get(msg.connId);
        if (route?.peer) {
          const peerProc = this.processes.get(route.peer.pid);
          peerProc?.worker.postMessage({
            type: 'tcp-data', connId: route.peer.connId, bytes: msg.bytes,
          });
        } else if (route?.preview) {
          route.preview.postMessage({ type: 'data', bytes: msg.bytes });
        }
        break;
      }
      case 'tcp-close':
      case 'tcp-shutdown': {
        const route = this.connections.get(msg.connId);
        if (route) {
          if (route.peer) {
            const peerProc = this.processes.get(route.peer.pid);
            peerProc?.worker.postMessage({ type: 'tcp-eof', connId: route.peer.connId });
          } else if (route.preview) {
            route.preview.postMessage({ type: 'end' });
            this.connections.delete(msg.connId);
          }
          if (msg.type === 'tcp-close') this.connections.delete(msg.connId);
        }
        break;
      }
      case 'tcp-unaccepted': {
        // Nobody was listening in that kernel — drop silently.
        break;
      }
    }
  }

  /** Deliver a child's piped output bytes (fd 1/2) to the pipe's reader:
   *  a guest parent process or — for parentPid 0 — the host (facade). */
  private deliverPipeOutput(pipeId: number, route: PipeRoute, bytes: Uint8Array | undefined): void {
    if (!bytes) return;
    if (route.parentPid === 0) {
      this.hostPipeSinks.get(pipeId)?.push(bytes);
      return;
    }
    const parent = this.processes.get(route.parentPid);
    parent?.worker.postMessage({ type: 'pipe-data', pipeId, bytes });
  }

  /** Close a host-owned pipe end (stream EOF) and forget its route. */
  private closeHostPipe(pipeId: number): void {
    const sink = this.hostPipeSinks.get(pipeId);
    if (sink) {
      this.hostPipeSinks.delete(pipeId);
      sink.close();
    }
    this.pipes.delete(pipeId);
  }

  private onProcessExit(proc: KernelProcess, code: number, signal: string | null) {
    if (proc.exited) return;
    proc.exited = true;
    proc.exitCode = code;
    proc.exitSignal = signal;
    const wasForeground = this.foregroundPid === proc.pid;
    if (wasForeground) {
      // A tty-inheriting child hands the terminal back to its parent (the
      // parent may still be mid-run — e.g. npx waiting on create-vite); the
      // shell-spawned case has no live parent and returns to null (prompt).
      const parent = proc.parentPid !== null ? this.processes.get(proc.parentPid) : undefined;
      this.foregroundPid = parent && !parent.exited ? proc.parentPid : null;
    }

    // Notify the parent (guest child_process sees exit + pipe EOFs).
    if (proc.parentPid !== null) {
      const parent = this.processes.get(proc.parentPid);
      parent?.worker.postMessage({ type: 'child-exit', pid: proc.pid, code, signal });
      for (const [pipeId, route] of this.pipes) {
        if (route.childPid === proc.pid && route.fd > 0) {
          parent?.worker.postMessage({ type: 'pipe-eof', pipeId });
        }
      }
      parent?.children.delete(proc.pid);
    }

    // Host-owned pipes (facade processes): the streams see EOF now.
    for (const [pipeId, route] of [...this.pipes]) {
      if (route.childPid === proc.pid && route.parentPid === 0 && route.fd > 0) {
        this.closeHostPipe(pipeId);
      }
    }

    // Close virtual connections owned by this process.
    for (const [connId, route] of [...this.connections]) {
      if (route.ownerPid === proc.pid) {
        if (route.peer) {
          const peerProc = this.processes.get(route.peer.pid);
          peerProc?.worker.postMessage({ type: 'tcp-eof', connId: route.peer.connId });
        } else if (route.preview) {
          route.preview.postMessage({ type: 'end' });
        }
        this.connections.delete(connId);
      }
    }
    // Release ports this process owned.
    let portsChanged = false;
    for (const [port, entry] of [...this.ports]) {
      if (entry.pid === proc.pid) {
        this.ports.delete(port);
        portsChanged = true;
        this.emit('unlisten', { port, pid: proc.pid });
      }
    }
    if (portsChanged) this.broadcastPorts();
    // Drop pipe routes whose child was this process.
    for (const [pipeId, route] of [...this.pipes]) {
      if (route.childPid === proc.pid) this.pipes.delete(pipeId);
    }

    // Flush pending RPCs (they are complete by definition).
    for (const p of proc.pending.values()) p.resolve();
    proc.pending.clear();

    this.emit('exit', {
      pid: proc.pid, code: signal ? null : code, signal, foreground: wasForeground,
    });

    // Schedule persistence (the keeper serves the OPFS write), then free
    // the worker. Foreground processes terminate after a tiny delay so any
    // final stdio postMessages land first (FIFO guarantees ordering).
    const terminate = () => {
      if (proc.pid === 1) return; // keeper lives for the session
      if (!proc.exited) return;
      try { proc.worker.terminate(); } catch { /* already gone */ }
      this.processes.delete(proc.pid);
    };
    setTimeout(terminate, 0);
  }

  // ---------------------------------------------------------- child spawning
  private onChildSpawn(parent: KernelProcess, req: any) {
    if (this.processes.size >= MAX_LIVE_PROCESSES + 1) {
      parent.worker.postMessage({ type: 'child-exit', pid: req.pid, code: -11 }); // EAGAIN
      return;
    }
    // Resolve the entry: file === null → the node interpreter itself.
    let entry: EntrySpec | null;
    let argv: string[];
    if (req.file === null || req.file === undefined) {
      const nodeArgs: string[] = req.nodeArgs ?? [];
      const first = nodeArgs[0] ?? '';
      if (first === '-v' || first === '--version') {
        entry = { type: 'version' };
        argv = ['/usr/local/bin/node', first];
      } else if (first === '-e' || first === '--eval') {
        entry = { type: 'eval', code: nodeArgs.slice(1).join(' ') };
        argv = ['/usr/local/bin/node', ...nodeArgs];
      } else if (first === '-p' || first === '--print') {
        entry = { type: 'eval', code: nodeArgs.slice(1).join(' '), print: true };
        argv = ['/usr/local/bin/node', ...nodeArgs];
      } else if (first === '' || first === '-i' || first === '--interactive') {
        entry = { type: 'repl' };
        argv = ['/usr/local/bin/node'];
      } else {
        entry = {
          type: 'main',
          path: first.startsWith('/') ? first : `${req.cwd}/${first}`,
        };
        argv = ['/usr/local/bin/node', first, ...nodeArgs.slice(1)];
      }
    } else {
      entry = { type: 'main', path: req.file };
      argv = ['/usr/local/bin/node', req.file, ...(req.args ?? [])];
    }

    // stdio: pipes get routes; 'inherit' copies the PARENT's fd spec (that
    // is what sharing a descriptor means — same tty or same upstream pipe).
    const childStdio = [];
    for (let i = 0; i < (req.stdio ?? []).length; i++) {
      const s = req.stdio[i];
      if (s.type === 'pipe') {
        childStdio.push({ type: 'pipe', pipeId: s.pipeId });
        this.pipes.set(s.pipeId, {
          parentPid: parent.pid, childPid: req.pid, fd: i,
        });
      } else if (s.type === 'inherit') {
        // Share the PARENT's fd (same tty or same upstream pipe).
        childStdio.push({ ...(parent.stdio[i] ?? { type: 'ignore' }) });
      } else {
        childStdio.push({ type: 'ignore' });
      }
    }

    const child = this.createProcess({
      pid: req.pid,
      parentPid: parent.pid,
      stdio: childStdio,
      entry,
      env: req.env,
      cwd: req.cwd,
      argv,
      repl: entry?.type === 'repl',
      background: true, // guest children are never the terminal foreground…
    });
    // …EXCEPT interactive ones: a child that INHERITS the parent's tty stdin
    // while the parent is the foreground process owns the terminal's input
    // from here on (a real terminal hands the tty to the foreground process
    // GROUP — the deepest reader gets the keystrokes). Without this, every
    // `npx create-…`-style interactive CLI dead-ends at its first prompt:
    // the parent (npx) never reads stdin, the child never receives it.
    if (this.foregroundPid === parent.pid && childStdio[0]?.type === 'tty') {
      this.foregroundPid = req.pid;
    }
    void child.ready.catch(() => {
      parent.worker.postMessage({ type: 'child-exit', pid: req.pid, code: 1, signal: null });
    });
  }

  // ----------------------------------------------------------- outbound net
  private onOutboundConnect(proc: KernelProcess, msg: any) {
    const port = msg.port | 0;
    const connId = msg.connId | 0;
    const target = this.ports.get(port);
    if (!target) {
      proc.worker.postMessage({ type: 'tcp-connect-failed', reqId: msg.reqId });
      return;
    }
    // Local pair: client side in `proc`, server side in the listener.
    const serverConnId = this.nextConnId++;
    this.connections.set(connId, {
      ownerPid: proc.pid, peer: { pid: target.pid, connId: serverConnId }, preview: null,
    });
    this.connections.set(serverConnId, {
      ownerPid: target.pid, peer: { pid: proc.pid, connId }, preview: null,
    });
    const listener = this.processes.get(target.pid);
    listener?.worker.postMessage({
      type: 'tcp-connect', port, connId: serverConnId, remotePort: 0,
    });
    proc.worker.postMessage({ type: 'tcp-connected', reqId: msg.reqId, status: 0 });
  }

  /** Preview bridge: SW/page hands us a raw virtual connection to a port.
   *  `initialBytes` is the client's request head+body (the SW builds the full
   *  HTTP/1.1 wire bytes and sends them with the connection request). */
  connectPreview(port: number, channel: MessagePort, initialBytes?: Uint8Array | null): boolean {
    const target = this.ports.get(port);
    if (!target) return false;
    const serverConnId = this.nextConnId++;
    this.connections.set(serverConnId, {
      ownerPid: target.pid, peer: null, preview: channel,
    });
    channel.onmessage = (ev: MessageEvent) => {
      const m = ev.data;
      if (m.type === 'data') {
        const listener = this.processes.get(target.pid);
        listener?.worker.postMessage({
          type: 'tcp-data', connId: serverConnId, bytes: new Uint8Array(m.bytes),
        });
      } else if (m.type === 'end') {
        const listener = this.processes.get(target.pid);
        listener?.worker.postMessage({ type: 'tcp-eof', connId: serverConnId });
        this.connections.delete(serverConnId);
      }
    };
    const listener = this.processes.get(target.pid);
    // The request bytes arrived WITH the connection setup (same packet as a
    // real TCP accept often is) — deliver them in the SAME message as the
    // connect (S3.1: one worker hop instead of two; the kernel delivers them
    // to the accepted socket before the server can install its data handler,
    // so the http.Server never sees a connection that never speaks).
    listener?.worker.postMessage({
      type: 'tcp-connect', port, connId: serverConnId, remotePort: 0,
      bytes: initialBytes && initialBytes.byteLength > 0 ? initialBytes : undefined,
    });
    return true;
  }

  private broadcastPorts(): void {
    const ports = [...this.ports.keys()];
    for (const proc of this.processes.values()) {
      if (!proc.exited) {
        proc.worker.postMessage({ type: 'ports-update', ports });
      }
    }
  }

  // ------------------------------------------------------------- kill/signal
  /** Deliver a signal: SIGINT goes through JS semantics; TERM/KILL hard-
   *  terminate the worker (the closest browser equivalent of a hard kill). */
  killProcess(pid: number, signal: string): boolean {
    const proc = this.processes.get(pid);
    if (!proc || proc.exited) return false;
    if (signal === 'SIGINT' || signal === 'SIGHUP' || signal === 'SIGQUIT') {
      proc.worker.postMessage({ type: 'signal', sig: signal });
      return true;
    }
    // SIGTERM / SIGKILL: terminate the worker. The exit surfaces with the
    // signal name (node reports exitCode null + signal).
    proc.worker.terminate();
    this.onProcessExit(proc, 0, signal);
    return true;
  }

  signalForeground(sig: string): boolean {
    if (this.foregroundPid === null) return false;
    return this.killProcess(this.foregroundPid, sig);
  }

  // ------------------------------------------------------------------ VFS
  private applyDeltas(source: KernelProcess, ops: Array<Record<string, any>>): void {
    for (const op of ops) {
      const recordAncestorDirs = (p: string) => {
        // The snapshot's dir set must cover every intermediate directory —
        // spawned processes hydrate from it, and importTree cannot place a
        // file whose parent is absent (node's fs semantics: no implicit
        // mkdir -p on write).
        const segs = String(p).split('/');
        for (let i = 2; i < segs.length; i++) {
          this.vfsSnapshot.dirs.add(segs.slice(0, i).join('/'));
        }
      };
      switch (op.type) {
        case 'write':
          this.vfsSnapshot.files.set(op.path, op.data);
          this.vfsSnapshot.symlinks.delete(op.path);
          this.vfsSnapshot.dirs.delete(op.path);
          recordAncestorDirs(op.path);
          break;
        case 'mkdir':
          this.vfsSnapshot.dirs.add(op.path);
          recordAncestorDirs(op.path);
          break;
        case 'symlink':
          this.vfsSnapshot.symlinks.set(op.path, op.target);
          recordAncestorDirs(op.path);
          break;
        case 'unlink': {
          this.vfsSnapshot.files.delete(op.path);
          this.vfsSnapshot.symlinks.delete(op.path);
          this.vfsSnapshot.dirs.delete(op.path);
          const prefix = op.path + '/';
          for (const p of [...this.vfsSnapshot.files.keys()]) {
            if (p.startsWith(prefix)) this.vfsSnapshot.files.delete(p);
          }
          for (const p of [...this.vfsSnapshot.symlinks.keys()]) {
            if (p.startsWith(prefix)) this.vfsSnapshot.symlinks.delete(p);
          }
          for (const d of [...this.vfsSnapshot.dirs]) {
            if (d.startsWith(prefix)) this.vfsSnapshot.dirs.delete(d);
          }
          break;
        }
        case 'rename': {
          const { from, to } = op;
          const renameKey = (p: string): string => (p === from ? to : to + p.slice(from.length));
          // Exact file at the source path.
          const data = this.vfsSnapshot.files.get(from);
          if (data !== undefined) {
            this.vfsSnapshot.files.delete(from);
            this.vfsSnapshot.files.set(to, data);
          }
          // DIRECTORY renames move the whole subtree (pnpm imports packages
          // through a temp dir: lodash_tmp_2_1 → lodash — a one-file rename
          // handler left the entire tree stranded under the temp name).
          const prefix = from + '/';
          for (const p of [...this.vfsSnapshot.files.keys()]) {
            if (p.startsWith(prefix)) {
              const d = this.vfsSnapshot.files.get(p)!;
              this.vfsSnapshot.files.delete(p);
              this.vfsSnapshot.files.set(renameKey(p), d);
            }
          }
          for (const p of [...this.vfsSnapshot.symlinks.keys()]) {
            if (p === from || p.startsWith(prefix)) {
              const t = this.vfsSnapshot.symlinks.get(p)!;
              this.vfsSnapshot.symlinks.delete(p);
              this.vfsSnapshot.symlinks.set(renameKey(p), t);
            }
          }
          for (const d of [...this.vfsSnapshot.dirs]) {
            if (d === from || d.startsWith(prefix)) {
              this.vfsSnapshot.dirs.delete(d);
              this.vfsSnapshot.dirs.add(renameKey(d));
            }
          }
          recordAncestorDirs(to);
          break;
        }
      }
    }
    if (ops.length > 0) this.snapshotDirty = true;
    // Fan out to every OTHER live process (cross-process visibility).
    for (const proc of this.processes.values()) {
      if (proc !== source && !proc.exited) {
        proc.worker.postMessage({ type: 'vfs-apply', ops });
      }
    }
    if (ops.length > 0) this.schedulePersist();
  }

  /** Host-side write (editor bridge): snapshot + fan-out.
   *  The keeper's OWN VFS must receive the write too — it is the process
   *  that performs the OPFS full-tree save, and applyDeltas treats it as the
   *  delta SOURCE (fan-out skips the source). Skipping the write-file RPC
   *  made host-written files vanish from OPFS on the next reload while
   *  guest-written files (real deltas) survived. */
  async writeFile(path: string, content: string): Promise<void> {
    const target = this.keeper ?? this.processes.values().next().value!;
    if (target && !target.exited) {
      await this.postTo(target, { type: 'write-file', path, content });
    }
    this.applyDeltas(target, [
      { type: 'write', path, data: new TextEncoder().encode(content) },
    ]);
  }

  // ------------------------------------------------- IDE filesystem RPCs
  // All served by the shell keeper (pid 1) — the always-alive process that
  // owns OPFS persistence. Mutations additionally fold into the host
  // snapshot and fan out to every other live process (cross-process
  // visibility, exactly like guest-initiated writes).

  /** Data-carrying RPC to a kernel process (see worker 'rpc-result'). */
  private rpcTo<T>(proc: KernelProcess, msg: any): Promise<T> {
    return new Promise<T>((resolve, reject) => {
      const id = (proc as any)._nextId ?? ((proc as any)._nextId = 1);
      (proc as any)._nextId = id + 1;
      proc.pending.set(id, { resolve: resolve as () => void, reject });
      proc.worker.postMessage({ ...msg, id });
    });
  }

  private fsTarget(): KernelProcess {
    const t = this.keeper ?? this.processes.values().next().value;
    if (!t || t.exited) throw new FsRpcError('ESRCH', 'kernel keeper not available');
    return t;
  }

  /** Read a file's raw bytes. Throws FsRpcError (ENOENT/EISDIR…). */
  async readFile(path: string): Promise<Uint8Array> {
    const r = await this.rpcTo<{ data: Uint8Array }>(this.fsTarget(), { type: 'fs-read', path });
    return r.data;
  }

  /** Read a file as text (UTF-8). */
  async readTextFile(path: string): Promise<string> {
    return new TextDecoder().decode(await this.readFile(path));
  }

  /** List a directory: names + kind + size + mtime. */
  async readdir(path: string): Promise<Array<{ name: string; kind: 'file' | 'dir' | 'symlink'; size: number; mtimeMs: number }>> {
    const r = await this.rpcTo<{ entries: Array<{ name: string; kind: 'file' | 'dir' | 'symlink'; size: number; mtimeMs: number }> }>(
      this.fsTarget(), { type: 'fs-readdir', path },
    );
    return r.entries;
  }

  /** Stat one path (lstat semantics — symlinks not followed). null if missing. */
  async stat(path: string): Promise<{ kind: 'file' | 'dir' | 'symlink'; size: number; mtimeMs: number; mode: number } | null> {
    const r = await this.rpcTo<{ stat: any }>(this.fsTarget(), { type: 'fs-stat', path });
    return r.stat ?? null;
  }

  /** Apply host-initiated mutations atomically-ish (batched). Ops run in the
   *  keeper through the real VFS methods (watchers fire, OPFS deltas queue),
   *  then fold into the snapshot + fan out to every live process. */
  async applyFsOps(ops: Array<Record<string, any>>): Promise<void> {
    const target = this.fsTarget();
    await this.rpcTo(target, { type: 'fs-apply-ops', ops });
    this.applyDeltas(target, ops as any);
  }

  async mkdir(path: string): Promise<void> {
    await this.applyFsOps([{ type: 'mkdir', path }]);
  }

  async rm(path: string, opts: { recursive?: boolean } = {}): Promise<void> {
    await this.applyFsOps([{ type: 'unlink', path, recursive: opts.recursive !== false }]);
  }

  async rename(from: string, to: string): Promise<void> {
    await this.applyFsOps([{ type: 'rename', from, to }]);
  }

  async writeBinaryFile(path: string, data: Uint8Array): Promise<void> {
    await this.applyFsOps([{ type: 'write', path, data }]);
  }

  /** Watch a directory through the keeper's VFS. Returns an unwatch fn. */
  async watch(path: string, cb: (event: { type: 'rename' | 'change'; filename: string | null }) => void): Promise<() => void> {
    const watchId = this.nextWatchId++;
    this.fsWatchers.set(watchId, cb);
    await this.rpcTo(this.fsTarget(), { type: 'fs-watch', path, watchId });
    return () => {
      this.fsWatchers.delete(watchId);
      const t = this.keeper;
      if (t && !t.exited) t.worker.postMessage({ type: 'fs-unwatch', watchId });
    };
  }

  /** Export a VFS subtree (project export / ZIP). */
  async exportTree(dir: string): Promise<{ dirs: string[]; files: Array<[string, Uint8Array]>; symlinks: Array<[string, string]> }> {
    const r = await this.rpcTo<{ tree: any }>(this.fsTarget(), { type: 'fs-tree', dir });
    return r.tree;
  }

  /** Import a VFS subtree (project import). Paths are used verbatim. */
  async importTree(tree: { dirs: string[]; files: Array<[string, Uint8Array]>; symlinks: Array<[string, string]> }): Promise<void> {
    const ops: Array<Record<string, any>> = [];
    for (const d of tree.dirs) ops.push({ type: 'mkdir', path: d });
    for (const [p, data] of tree.files) ops.push({ type: 'write', path: p, data });
    for (const [p, target] of tree.symlinks) ops.push({ type: 'symlink', path: p, target });
    // Batched in chunks so one postMessage never carries a whole repo.
    const CHUNK = 400;
    for (let i = 0; i < ops.length; i += CHUNK) {
      await this.applyFsOps(ops.slice(i, i + CHUNK));
    }
  }

  /** Aggregated runtime diagnostics (real measurements only). */
  async getDiagnostics(): Promise<Record<string, any>> {
    const base: Record<string, any> = {
      nodeVersion: this.nodeVersion,
      bootMs: this.bootMs,
      bootPhases: (globalThis as any).__ocBootPhases ?? null,
      processCount: 0,
      processes: [] as Array<Record<string, any>>,
      ports: this.listeningPorts(),
      workerCount: 0,
      mainThreadHeap: (performance as any).memory
        ? {
            usedJSHeapMB: +(((performance as any).memory.usedJSHeapSize / 1048576).toFixed(1)),
            totalJSHeapMB: +(((performance as any).memory.totalJSHeapSize / 1048576).toFixed(1)),
          }
        : null,
    };
    for (const p of this.ps()) {
      base.processes.push(p);
      if (!p.exited) base.processCount++;
    }
    base.workerCount = this.processes.size;
    try {
      const t = this.fsTarget();
      const diag = await this.rpcTo<Record<string, any>>(t, { type: 'diag' });
      base.vfs = diag;
    } catch { /* keeper gone */ }
    return base;
  }

  private schedulePersist(): void {
    if (this.persistTimer !== null) return;
    this.persistTimer = setTimeout(() => {
      this.persistTimer = null;
      void this.persist().catch(() => { /* best-effort */ });
    }, 1500);
  }

  /** Full-tree OPFS save through the shell keeper (worker-only OPFS API). */
  async persist(): Promise<void> {
    if (!this.snapshotDirty || !this.keeper || this.keeper.exited) return;
    await this.postTo(this.keeper, { type: 'persist-vfs' });
    this.snapshotDirty = false;
  }

  private postTo(proc: KernelProcess, msg: any): Promise<void> {
    return new Promise((resolve, reject) => {
      const id = (proc as any)._nextId ?? ((proc as any)._nextId = 1);
      (proc as any)._nextId = id + 1;
      proc.pending.set(id, { resolve, reject });
      proc.worker.postMessage({ ...msg, id });
    });
  }

  private adoptSnapshot(tree: { dirs: string[]; files: Array<[string, unknown]>; symlinks: Array<[string, string]> }): void {
    this.vfsSnapshot = {
      dirs: new Set(tree.dirs ?? []),
      files: new Map((tree.files ?? []).map(([p, d]: [string, any]) => [p, d as Uint8Array])),
      symlinks: new Map(tree.symlinks ?? []),
    };
  }

  private snapshotPayload(): any {
    if (this.vfsSnapshot.files.size === 0 && this.vfsSnapshot.dirs.size === 0
      && this.vfsSnapshot.symlinks.size === 0) {
      return null;
    }
    return {
      dirs: [...this.vfsSnapshot.dirs],
      files: [...this.vfsSnapshot.files.entries()],
      symlinks: [...this.vfsSnapshot.symlinks.entries()],
    };
  }

  // ------------------------------------------------------------------ shell
  /** Spawn a terminal command as a new FOREGROUND process. */
  async spawn(command: string, opts: { background?: boolean } = {}): Promise<void> {
    await this.ready;
    const { cmd, args } = parseCommand(command);
    const background = opts.background === true;
    const spec = this.resolveShellCommand(cmd, args);
    if (spec.error) {
      this.emit('stdio', 2, `${spec.error}\n`);
      this.emit('exit', { pid: -1, code: 127, signal: null, foreground: !background });
      return;
    }
    const repl = spec.entry?.type === 'repl';
    const proc = this.createProcess({
      pid: this.nextPid++,
      parentPid: null,
      stdio: background
        ? [{ type: 'ignore' }, { type: 'tty' }, { type: 'tty' }]
        : [{ type: 'tty' }, { type: 'tty' }, { type: 'tty' }],
      entry: spec.entry,
      env: spec.env,
      cwd: this.cwd,
      argv: spec.argv,
      repl,
      background,
    });
    if (!background) this.foregroundPid = proc.pid;
    this.emit('processStart', { pid: proc.pid, repl, background });
    if (background) return; // prompt returns immediately
    // Foreground: resolve when the process exits (terminal prompt authority).
    await new Promise<void>((resolve) => {
      const off = this.on('exit', (info) => {
        if (info.pid === proc.pid) { off(); resolve(); }
      });
    });
  }

  // ------------------------------------------------------- programmatic spawn
  /**
   * Spawn a command as a PIPE-STDIO process owned by the HOST — the
   * WebContainer-API process shape (exit/input/output/kill/resize), no
   * terminal involvement. Used by the WebContainer facade.
   *
   * Command resolution is the same as the terminal spawn (internal bins,
   * node -e/-p/script forms, PATH + node_modules/.bin walk-up) but resolves
   * script paths against `opts.cwd` when given.
   */
  async spawnProgram(
    command: string,
    args: string[],
    opts: {
      cwd?: string;
      env?: Record<string, string>;
      terminal?: { cols: number; rows: number };
    } = {},
  ): Promise<ProgramHandle> {
    await this.ready;
    const cwd = opts.cwd ?? this.cwd;
    const prevCwd = this.cwd;
    if (opts.cwd) this.cwd = opts.cwd; // resolveShellCommand resolves via cwd
    let spec: ReturnType<OpenContainerRuntime['resolveShellCommand']>;
    try {
      spec = this.resolveShellCommand(command, args);
    } finally {
      if (opts.cwd) this.cwd = prevCwd;
    }
    if (spec.error || !spec.entry) {
      throw new Error(spec.error ?? `OpenContainer: cannot spawn '${command}'`);
    }
    const pid = this.nextPid++;
    const stdinId = this.nextHostPipeId++;
    const stdoutId = this.nextHostPipeId++;
    const stderrId = this.nextHostPipeId++;
    const proc = this.createProcess({
      pid,
      parentPid: null,
      stdio: [
        { type: 'pipe', pipeId: stdinId },
        { type: 'pipe', pipeId: stdoutId },
        { type: 'pipe', pipeId: stderrId },
      ],
      entry: spec.entry,
      env: opts.env ? { ...spec.env, ...opts.env } : spec.env,
      cwd,
      argv: spec.argv,
      repl: spec.entry.type === 'repl',
      background: true,
    });
    for (const [pipeId, fd] of [[stdinId, 0], [stdoutId, 1], [stderrId, 2]] as const) {
      this.pipes.set(pipeId, { parentPid: 0, childPid: pid, fd });
    }

    // Output streams: `output` merges fd1+fd2 (WebContainer drop-in
    // semantics); `stderr` is fd2-only (OpenContainer extension).
    const decoder = new TextDecoder();
    let outCtrl: ReadableStreamDefaultController<string> | null = null;
    let errCtrl: ReadableStreamDefaultController<string> | null = null;
    for (const pipeId of [stdoutId, stderrId]) {
      this.hostPipeSinks.set(pipeId, {
        push: (bytes) => {
          const text = decoder.decode(bytes, { stream: true });
          if (text) {
            outCtrl?.enqueue(text); // merged output (drop-in)
            if (pipeId === stderrId) errCtrl?.enqueue(text);
          }
        },
        close: () => {
          if (pipeId === stdoutId) {
            try { outCtrl?.close(); } catch { /* already closed */ }
          } else {
            try { errCtrl?.close(); } catch { /* already closed */ }
          }
        },
      });
    }
    const output = new ReadableStream<string>({
      start(c) { outCtrl = c; },
      cancel() { outCtrl = null; },
    });
    const stderr = new ReadableStream<string>({
      start(c) { errCtrl = c; },
      cancel() { errCtrl = null; },
    });

    const input = new WritableStream<string>({
      write: (chunk) => {
        if (!proc.exited) proc.worker.postMessage({ type: 'stdin', data: chunk });
      },
      close: () => {
        if (!proc.exited) proc.worker.postMessage({ type: 'stdin-eof' });
      },
    });

    const exit = new Promise<number>((resolve) => {
      const off = this.on('exit', (info) => {
        if (info.pid === pid) {
          off();
          resolve(info.code ?? 0);
        }
      });
    });

    this.emit('processStart', { pid, repl: spec.entry.type === 'repl', background: true });
    if (opts.terminal) {
      proc.worker.postMessage({ type: 'resize', cols: opts.terminal.cols, rows: opts.terminal.rows });
    }

    return {
      pid,
      exit,
      input,
      output,
      stderr,
      resize: (size: { cols: number; rows: number }) => {
        if (!proc.exited) proc.worker.postMessage({ type: 'resize', cols: size.cols, rows: size.rows });
      },
      kill: () => { this.killProcess(pid, 'SIGTERM'); },
    };
  }

  /** Resolve a shell command against the internal bins + VFS PATH. */
  private resolveShellCommand(cmd: string, args: string[]): {
    entry: EntrySpec | null; argv?: string[]; env?: Record<string, string>;
    cwd?: string; error?: string;
  } {
    const INTERNAL = new Set(['node', 'npm', 'npx', 'pnpm', 'pnpx', 'corepack', 'sh', 'bash', 'clear', 'help']);
    if (cmd === 'clear' || cmd === 'help') {
      return { entry: null, error: undefined };
    }
    if (INTERNAL.has(cmd)) {
      if (cmd === 'node') {
        const first = args[0] ?? '';
        if (args.length === 0 || first === '-i' || first === '--interactive') {
          return { entry: { type: 'repl' }, argv: ['node'] };
        }
        if (first === '-v' || first === '--version') {
          return { entry: { type: 'version' }, argv: ['/usr/local/bin/node', first] };
        }
        // Real node -e semantics (doc/api/cli.md): the FIRST argument after
        // -e is the script; every following argument goes to process.argv
        // (argv[1] = first extra — `node -e 'x' -- foo` sees argv[1] === 'foo',
        // the '--' option terminator itself is consumed). The eval script
        // itself never appears in argv, and neither does -e.
        if (first === '-e' || first === '--eval') {
          const extras = args.slice(2);
          if (extras[0] === '--') extras.shift();
          return { entry: { type: 'eval', code: args[1] ?? '' }, argv: ['/usr/local/bin/node', ...extras] };
        }
        if (first === '-p' || first === '--print') {
          const extras = args.slice(2);
          if (extras[0] === '--') extras.shift();
          return { entry: { type: 'eval', code: args[1] ?? '', print: true }, argv: ['/usr/local/bin/node', ...extras] };
        }
        // node <script> — resolve against the shell's cwd.
        const path = this.resolveInCwd(first);
        if (!this.snapshotHas(path)) {
          return { entry: null, error: `node: cannot find module '${first}'` };
        }
        return { entry: { type: 'main', path }, argv: ['/usr/local/bin/node', first, ...args.slice(1)] };
      }
      // npm/npx/pnpm/pnpx/corepack/sh/bash → their bin shims run as mains.
      // S9 fix: the sh shim lives at /usr/bin/sh (boot.ts mounts it there —
      // /usr/local/bin is npm/pnpm/corepack territory); typing `sh` at the
      // prompt used to die with MODULE_NOT_FOUND.
      const bin = cmd === 'sh' || cmd === 'bash' ? '/usr/bin/sh' : `/usr/local/bin/${cmd}`;
      return {
        entry: { type: 'main', path: bin },
        argv: ['/usr/local/bin/node', bin, ...args],
      };
    }
    // PATH lookup in the VFS snapshot (node_modules/.bin walk-up from cwd).
    const found = this.resolveOnPath(cmd);
    if (!found) {
      return {
        entry: null,
        error: `OpenContainer: command not found: ${cmd} (PATH: /usr/local/bin:/usr/bin:/bin + node_modules/.bin)`,
      };
    }
    // Shebang dispatch (the execve step): node shebangs run under node.
    const shebang = this.readShebang(found);
    if (shebang && /node(\.exe)?$/.test(shebang.split('/').pop() ?? '')) {
      return {
        entry: { type: 'main', path: found },
        argv: ['/usr/local/bin/node', found, ...args],
      };
    }
    if (shebang && /(ba|da|z)?sh$/.test(shebang.split('/').pop() ?? '')) {
      const shBin = '/usr/bin/sh';
      return {
        entry: { type: 'main', path: shBin },
        argv: ['/usr/local/bin/node', shBin, ...args],
      };
    }
    return {
      entry: null,
      error: `OpenContainer: ${cmd}: no recognized interpreter (shebang ${shebang ?? 'none'}) — only node and sh programs execute in the browser runtime`,
    };
  }

  /** Resolve a possibly-relative path against the shell's cwd. */
  private resolveInCwd(p: string): string {
    if (p.startsWith('/')) return this.normalizePath(p);
    return this.normalizePath(`${this.cwd}/${p}`);
  }

  /** Lexical path normalization (., .., duplicate slashes). */
  private normalizePath(p: string): string {
    const out: string[] = [];
    for (const seg of p.split('/')) {
      if (seg === '' || seg === '.') continue;
      if (seg === '..') { out.pop(); continue; }
      out.push(seg);
    }
    return '/' + out.join('/');
  }

  /** The shell's `cd`: resolve, validate against the snapshot, switch.
   *  Returns the new cwd, or null + reason when the target is missing/not a
   *  directory. Bash-compatible argument handling for the common cases. */
  chdir(dir: string | undefined): { ok: true; cwd: string } | { ok: false; error: string } {
    let target: string;
    if (dir === undefined || dir === '~') {
      target = '/home/node';               // $HOME (worker env)
    } else if (dir === '-') {
      return { ok: false, error: 'cd: OLDPWD is not supported in this shell' };
    } else {
      target = this.resolveInCwd(dir);
    }
    if (this.vfsSnapshot.files.has(target) || this.vfsSnapshot.symlinks.has(target)) {
      return { ok: false, error: `cd: not a directory: ${dir}` };
    }
    // Base dirs exist in every kernel (boot mkdirs cwd; the image provides
    // the rest) even when the host snapshot has no explicit entry for them.
    const BASE_DIRS = new Set([
      '/', '/home', '/home/project', '/home/node', '/tmp', '/usr', '/usr/bin',
      '/usr/local', '/usr/local/bin', '/usr/lib', '/usr/lib/node_modules',
    ]);
    const isDir = BASE_DIRS.has(target) || this.vfsSnapshot.dirs.has(target);
    if (!isDir) {
      return { ok: false, error: `cd: no such file or directory: ${dir}` };
    }
    this.cwd = target;
    return { ok: true, cwd: target };
  }

  getCurrentCwd(): string { return this.cwd; }

  private snapshotHas(path: string): boolean {
    return this.vfsSnapshot.files.has(path) || this.vfsSnapshot.symlinks.has(path);
  }

  private resolveOnPath(cmd: string): string | null {
    const dirs = [
      `${this.cwd}/node_modules/.bin`,
      '/home/project/node_modules/.bin',
      '/home/node_modules/.bin',
      '/usr/local/bin', '/usr/bin', '/bin',
    ];
    for (const dir of dirs) {
      const p = `${dir}/${cmd}`;
      if (this.snapshotHas(p)) return p;
    }
    return null;
  }

  private readShebang(path: string): string | null {
    let data = this.vfsSnapshot.files.get(path);
    if (data === undefined) {
      // Symlink: resolve one level within the snapshot.
      const target = this.vfsSnapshot.symlinks.get(path);
      if (target) {
        const resolved = target.startsWith('/')
          ? target
          : normalizeDir(path, target);
        data = this.vfsSnapshot.files.get(resolved);
      }
    }
    if (!data) return null;
    const head = new TextDecoder().decode(data.subarray(0, 256));
    const m = /^#!([^\n\r]*)/.exec(head);
    return m ? m[1].trim() : null;
  }

  // ------------------------------------------------------------- terminal IO
  /** Raw keystrokes from the terminal → the FOREGROUND process stdin. */
  writeStdin(data: string): void {
    const pid = this.foregroundPid;
    if (pid === null) return;
    this.processes.get(pid)?.worker.postMessage({ type: 'stdin', data });
  }

  sendEof(): void {
    const pid = this.foregroundPid;
    if (pid === null) return;
    this.processes.get(pid)?.worker.postMessage({ type: 'stdin-eof' });
  }

  async resize(cols: number, rows: number): Promise<void> {
    for (const proc of this.processes.values()) {
      if (!proc.exited) {
        proc.worker.postMessage({ type: 'resize', cols, rows });
      }
    }
  }

  /** Run a CJS string like `node -e` as a new foreground process. */
  async runEval(code: string): Promise<void> {
    await this.spawn(`node -e ${quoteIfNeeded(code)}`);
  }

  async runMain(path: string): Promise<void> {
    await this.spawn(`node ${path}`);
  }

  /** Interactive `node` REPL attached to the tty. */
  async startRepl(): Promise<void> {
    await this.spawn('node');
  }

  // ------------------------------------------------------------------ misc
  on<K extends keyof RuntimeEventMap>(event: K, listener: RuntimeEventMap[K]): () => void {
    let set = this.listeners.get(event);
    if (!set) this.listeners.set(event, (set = new Set()));
    set.add(listener as (...args: never[]) => void);
    return () => { set!.delete(listener as (...args: never[]) => void); };
  }

  private emit<K extends keyof RuntimeEventMap>(event: K, ...args: Parameters<RuntimeEventMap[K]>) {
    const ctorKey = ('on' + event[0].toUpperCase() + event.slice(1)) as keyof RuntimeEvents;
    (this.events as any)[ctorKey]?.(...args);
    const set = this.listeners.get(event);
    if (set) for (const fn of [...set]) {
      try { (fn as any)(...args); } catch { /* listener errors never break the runtime */ }
    }
  }

  /** Compatibility: the old recycle is a no-op — every command is a fresh
   *  process now (node semantics). Kept for API consumers. */
  recycle(): Promise<void> {
    return Promise.resolve();
  }

  /** List live processes (jobs). */
  ps(): Array<{ pid: number; repl: boolean; background: boolean; ports: number[]; exited: boolean }> {
    return [...this.processes.values()].map((p) => ({
      pid: p.pid,
      repl: p.repl,
      background: p.background,
      ports: [...this.ports.entries()].filter(([, e]) => e.pid === p.pid).map(([port]) => port),
      exited: p.exited,
    }));
  }

  listeningPorts(): number[] {
    return [...this.ports.keys()];
  }

  teardown(): void {
    for (const proc of this.processes.values()) {
      try { proc.worker.terminate(); } catch { /* already gone */ }
      for (const p of proc.pending.values()) p.reject(new Error('runtime torn down'));
      proc.pending.clear();
    }
    this.processes.clear();
    this.pipes.clear();
    this.connections.clear();
    this.ports.clear();
    this.foregroundPid = null;
    this.exited = false;
  }

  // ----------------------------------------------------------------- preview
  /**
   * Register the preview ServiceWorker and wire the preview URL bridge
   * (`/opencontainer/p/<port>/…` → this runtime's virtual TCP stack).
   *
   * Called automatically by boot() — embedders normally never call this.
   * The SW file must live on THIS origin (browser spec: service workers
   * are same-origin only), so with the default CDN assetsBase the runtime
   * probes the conventional same-origin locations:
   *   /opencontainer/preview-sw.js   (the documented copy: `cp -r
   *                                   node_modules/opencontainer/public/opencontainer ./public/`
   *                                   — only needed for preview support)
   *   /preview-sw.js                 (flat-copy convention)
   * A same-origin assetsBase ({ assetsBase: '/opencontainer' }) is probed
   * first. Returns the registration, or null when no same-origin SW was
   * found (a console warning explains the copy step; everything except
   * preview URLs keeps working).
   */
  async registerPreview(): Promise<ServiceWorkerRegistration | null> {
    if (this.previewRegistered) return null;
    this.previewRegistered = true;
    if (typeof navigator === 'undefined' || !('serviceWorker' in navigator)) return null;

    const candidates: string[] = [];
    if (!/^https?:/.test(this.assetsBase)) {
      candidates.push(`${this.assetsBase}/preview-sw.js`);
    }
    candidates.push('/opencontainer/preview-sw.js', '/preview-sw.js');

    let registration: ServiceWorkerRegistration | null = null;
    let lastError: unknown = null;
    for (const path of candidates) {
      try {
        // Root scope lets the SW also serve the ESM graph transport
        // (/oc-esm/…). Hosts that refuse it (no Service-Worker-Allowed
        // header) get the default scope fallback — preview URLs live under
        // /opencontainer/ and keep working either way.
        try {
          registration = await navigator.serviceWorker.register(path, { scope: '/' });
        } catch {
          registration = await navigator.serviceWorker.register(path);
        }
        break;
      } catch (err) {
        lastError = err;
      }
    }
    if (!registration) {
      console.warn(
        '[opencontainer] preview ServiceWorker not registered ' +
        (lastError ? `(${(lastError as Error)?.message ?? lastError}) ` : '') +
        '— preview URLs need the SW on your origin. Copy the runtime assets to your public ' +
        'folder: cp -r node_modules/opencontainer/public/opencontainer ./public/ — everything ' +
        'else (terminal, fs, npm) works without it.',
      );
      return null;
    }
    await navigator.serviceWorker.ready;

    // Page-level runtime registry: the SW message handler below asks every
    // runtime on the page until one owns the port (multi-runtime pages,
    // e.g. a facade runtime booted next to a terminal runtime).
    const g = globalThis as any;
    if (!Array.isArray(g.__ocRuntimes)) g.__ocRuntimes = [];
    if (!g.__ocRuntimes.includes(this)) g.__ocRuntimes.push(this);

    // Route the SW's preview fetches into this runtime's virtual TCP.
    navigator.serviceWorker.addEventListener('message', (ev: MessageEvent) => {
      const m = ev.data;
      if (!m || m.type !== 'oc-preview-fetch') return;
      if ((ev as any).__ocHandled) return; // another runtime on this page took it
      const channel = ev.ports[0];
      const registry: OpenContainerRuntime[] = (globalThis as any).__ocRuntimes ?? [this];
      const owner = registry.find((r) => r.connectPreview(m.port, channel, m.bytes));
      (ev as any).__ocHandled = true;
      if (!owner) {
        try { channel.postMessage({ type: 'end' }); } catch { /* closed */ }
      }
    });

    // Preview iframes forward console errors here (via setPreviewScript's
    // injected shim) — re-emit as 'preview-message' for embedders.
    window.addEventListener('message', (ev: MessageEvent) => {
      const data: any = ev.data;
      if (data && typeof data.type === 'string' && data.type.startsWith('PREVIEW_')) {
        this.emit('previewMessage', data);
      }
    });

    // Deliver a preview script registered before the SW was ready.
    if (this.previewScript !== null) {
      this.postPreviewScript(this.previewScript, registration);
    }
    return registration;
  }

  /**
   * Inject a script into every guest-served HTML page (the upstream
   * WebContainer `setPreviewScript` contract: error forwarding, preview
   * tooling). The script runs FIRST in the page; posting
   * `{ type: 'PREVIEW_*', ... }` to window.parent surfaces as a
   * 'preview-message' event on the runtime / facade.
   */
  setPreviewScript(code: string): void {
    this.previewScript = code;
    const reg = navigator?.serviceWorker?.controller
      ? { active: navigator.serviceWorker.controller } as any
      : null;
    if (reg) this.postPreviewScript(code, reg);
  }

  private postPreviewScript(code: string, reg: { active: ServiceWorker | null }): void {
    try {
      reg.active?.postMessage({ type: 'oc-preview-script', code });
    } catch {
      /* SW not ready — redelivered on the next registerPreview */
    }
  }
}

function normalizeDir(fromPath: string, relTarget: string): string {
  const dirParts = fromPath.split('/').slice(0, -1);
  const targetParts = relTarget.split('/');
  const out: string[] = [];
  for (const part of [...dirParts, ...targetParts]) {
    if (part === '' || part === '.') continue;
    if (part === '..') out.pop();
    else out.push(part);
  }
  return '/' + out.join('/');
}

function quoteIfNeeded(code: string): string {
  return code.includes(' ') ? JSON.stringify(code) : code;
}

/** Quote-aware tokenizer (handles "a b" 'c d' and backslash escapes).
 *  Bash parity: inside double quotes \", \\, \$ and \` escape; inside single
 *  quotes NOTHING escapes (all literal). Outside quotes, \\ escapes any char. */
export function parseCommand(input: string): ParsedCommand {
  const out: string[] = [];
  let cur = '';
  let quote: '"' | "'" | null = null;
  for (let i = 0; i < input.length; i++) {
    const ch = input[i];
    if (quote) {
      if (ch === quote) quote = null;
      else if (quote === '"' && ch === '\\' && i + 1 < input.length) {
        // bash: only " \ $ ` are special after a backslash in double quotes;
        // every other backslash sequence stays literal (both characters).
        const next = input[i + 1];
        if (next === '"' || next === '\\' || next === '$' || next === '`') {
          cur += next;
          i++;
        } else {
          cur += ch;
        }
      }
      else cur += ch;
    } else if (ch === '"' || ch === "'") {
      quote = ch;
    } else if (ch === '\\' && i + 1 < input.length) {
      cur += input[++i];
    } else if (/\s/.test(ch)) {
      if (cur) { out.push(cur); cur = ''; }
    } else {
      cur += ch;
    }
  }
  if (cur) out.push(cur);
  return { cmd: out[0] ?? '', args: out.slice(1) };
}
